#!/bin/sh

# Without an upstream LNS there is nothing to proxy to, so the UDP backend
# listens only; with one it proxies. This has to be decided before
# GATEWAY_UDP_UPSTREAM_SERVER gets its fallback value below, which would make
# every run look like it has an LNS.
if [ -z "${GATEWAY_UDP_MODE}" ]; then
    if [ -z "${GATEWAY_UDP_UPSTREAM_SERVER}" ]; then
        GATEWAY_UDP_MODE=listen
    else
        GATEWAY_UDP_MODE=proxy
    fi
fi

# The default topic contains "}", which would end a ${VAR:=...} expansion
# early, so it is set explicitly. Only an unset variable gets the default.
if [ -z "${SNIFFER_MQTT_TOPIC+x}" ]; then
    SNIFFER_MQTT_TOPIC='lorawan-sniffer/{gateway_eui}/{direction}/{mtype}'
fi

: ${SNIFFER_LOG_LEVEL:=INFO}
: ${SNIFFER_API_BIND:=0.0.0.0:8888}
: ${SNIFFER_API_ALLOWED_HOSTS:=}
: ${SNIFFER_DATABASE_PATH:=/var/lib/lorawan-sniffer/sniffer.db}
: ${SNIFFER_DATABASE_RETENTION:=30days}
: ${SNIFFER_MQTT_ENABLED:=false}
: ${SNIFFER_MQTT_SERVER:=localhost}
: ${SNIFFER_MQTT_PORT:=1883}
: ${SNIFFER_MQTT_TLS:=false}
: ${SNIFFER_MQTT_CA_FILE:=}
: ${SNIFFER_MQTT_CLIENT_CERT_FILE:=}
: ${SNIFFER_MQTT_CLIENT_KEY_FILE:=}
: ${SNIFFER_MQTT_CLIENT_ID:=lorawan-sniffer}
: ${SNIFFER_MQTT_USERNAME:=}
: ${SNIFFER_MQTT_PASSWORD:=}
: ${SNIFFER_MQTT_QOS:=0}
: ${GATEWAY_PROTOCOL:=udp}
: ${GATEWAY_UDP_LISTEN_ACKS:=true}
: ${GATEWAY_UDP_SESSION_TIMEOUT:=5m}
: ${GATEWAY_UDP_MAX_GATEWAYS:=100}
: ${GATEWAY_UDP_DOWNSTREAM_BIND:=0.0.0.0:1700}
: ${GATEWAY_UDP_UPSTREAM_SERVER:=localhost}
: ${GATEWAY_UDP_UPSTREAM_PORT:=1700}
: ${GATEWAY_CONCENTRATORD_DOWNSTREAM_EVENT_URL:=ipc:///tmp/concentratord_event}
: ${GATEWAY_CONCENTRATORD_DOWNSTREAM_COMMAND_URL:=ipc:///tmp/concentratord_command}
: ${GATEWAY_CONCENTRATORD_UPSTREAM_EVENT_BIND:=ipc:///tmp/sniffer_event}
: ${GATEWAY_CONCENTRATORD_UPSTREAM_COMMAND_BIND:=ipc:///tmp/sniffer_command}

export SNIFFER_LOG_LEVEL SNIFFER_API_BIND SNIFFER_API_ALLOWED_HOSTS SNIFFER_DATABASE_PATH SNIFFER_DATABASE_RETENTION
export SNIFFER_MQTT_ENABLED SNIFFER_MQTT_SERVER SNIFFER_MQTT_PORT SNIFFER_MQTT_TLS
export SNIFFER_MQTT_CA_FILE SNIFFER_MQTT_CLIENT_CERT_FILE SNIFFER_MQTT_CLIENT_KEY_FILE
export SNIFFER_MQTT_CLIENT_ID SNIFFER_MQTT_USERNAME SNIFFER_MQTT_PASSWORD
export SNIFFER_MQTT_TOPIC SNIFFER_MQTT_QOS
export GATEWAY_PROTOCOL GATEWAY_UDP_MODE GATEWAY_UDP_LISTEN_ACKS GATEWAY_UDP_SESSION_TIMEOUT
export GATEWAY_UDP_MAX_GATEWAYS GATEWAY_UDP_DOWNSTREAM_BIND GATEWAY_UDP_UPSTREAM_SERVER GATEWAY_UDP_UPSTREAM_PORT
export GATEWAY_CONCENTRATORD_DOWNSTREAM_EVENT_URL GATEWAY_CONCENTRATORD_DOWNSTREAM_COMMAND_URL
export GATEWAY_CONCENTRATORD_UPSTREAM_EVENT_BIND GATEWAY_CONCENTRATORD_UPSTREAM_COMMAND_BIND

exec "$@"
